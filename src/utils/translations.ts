export const translateAbility = (name: string): string => {
  const clean = name.toLowerCase().trim()
  if (abilitiesEs[clean]) {
    return abilitiesEs[clean]
  }
  return clean.replace(/-/g, ' ').replace(/^./, (c) => c.toUpperCase())
}
